#!/usr/bin/env bash
# Regenerate <config-dir>/RESULTS.md from baseline_*.tsv + history_*.tsv files
# alongside it. Idempotent.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/lib.sh"

if [[ $# -lt 1 ]]; then
    cat <<'EOF' >&2
Usage: render_results.sh <config-dir>

Reads baseline_<scenario>.tsv and history_<scenario>.tsv files from the given
directory and writes RESULTS.md.
EOF
    exit 1
fi

DIR="$1"
[[ -d "$DIR" ]] || die "not a directory: $DIR"

OUT="${DIR%/}/RESULTS.md"
TMP="$(mktemp)"

# Collect scenario ids from baseline + history files (preserving discovery order).
declare -a SCENARIOS=()
declare -A SEEN=()

add_scenario() {
    local id="$1"
    if [[ -z "${SEEN[$id]:-}" ]]; then
        SEEN[$id]=1
        SCENARIOS+=("$id")
    fi
}

shopt -s nullglob
for f in "${DIR%/}"/baseline_*.tsv; do
    base="$(basename "$f")"
    id="${base#baseline_}"
    id="${id%.tsv}"
    add_scenario "$id"
done
for f in "${DIR%/}"/history_*.tsv; do
    base="$(basename "$f")"
    id="${base#history_}"
    id="${id%.tsv}"
    add_scenario "$id"
done
shopt -u nullglob

if [[ ${#SCENARIOS[@]} -eq 0 ]]; then
    log "no baseline_*.tsv or history_*.tsv in $DIR; nothing to render"
    rm -f "$TMP"
    exit 0
fi

dir_basename="$(basename "${DIR%/}")"

{
    printf '# Bench: %s\n\n' "$dir_basename"
    printf 'Auto-generated by `bench/scripts/render_results.sh`. Do not edit by hand — re-run `baseline.sh` or `measure.sh`.\n\n'

    for scenario in "${SCENARIOS[@]}"; do
        printf '## %s\n\n' "$scenario"

        baseline_file="${DIR%/}/baseline_${scenario}.tsv"
        if [[ -f "$baseline_file" ]]; then
            # Baseline columns:
            # 1 captured_at  2 runs  3-7 req(mean,median,std,min,max)
            # 8-12 p50(...)  13-17 p99(...)  18 nginx_version  19 kernel
            # 20 cpu  21 governor
            awk -F'\t' '
                NR == 1 {
                    printf "### nginx baseline (frozen)\n\n"
                    printf "Captured %s over %s iterations. nginx %s, kernel %s, %s, governor=%s.\n\n",
                        $1, $2, $18, $19, $20, $21
                    printf "| metric | mean | median | stddev | min | max |\n"
                    printf "| --- | ---: | ---: | ---: | ---: | ---: |\n"
                    printf "| req/s    | %.0f | %.0f | %.0f | %.0f | %.0f |\n", $3, $4, $5, $6, $7
                    printf "| p50 (ms) | %.3f | %.3f | %.3f | %.3f | %.3f |\n", $8, $9, $10, $11, $12
                    printf "| p99 (ms) | %.3f | %.3f | %.3f | %.3f | %.3f |\n", $13, $14, $15, $16, $17
                    printf "\n"
                }
            ' "$baseline_file"
        else
            printf '### nginx baseline (frozen)\n\n_No baseline captured yet._ Run: `bench/scripts/baseline.sh %s`\n\n' "$scenario"
        fi

        history_file="${DIR%/}/history_${scenario}.tsv"
        if [[ -f "$history_file" ]]; then
            printf '### ruxen history\n\n'
            printf '| date | commit | req/s | Δ req/s | p50 (ms) | Δ p50 | p99 (ms) | Δ p99 | non-2xx | note |\n'
            printf '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |\n'

            # Pull baseline medians (req/s, p50, p99) from baseline_file if present.
            local_base_req=""
            local_base_p50=""
            local_base_p99=""
            if [[ -f "$baseline_file" ]]; then
                IFS=$'\t' read -r _ _ _ b_req _ _ _ _ b_p50 _ _ _ _ b_p99 _ _ _ _ _ _ _ <"$baseline_file" || true
                local_base_req="$b_req"
                local_base_p50="$b_p50"
                local_base_p99="$b_p99"
            fi

            awk -F'\t' \
                -v br="${local_base_req:-0}" \
                -v bp50="${local_base_p50:-0}" \
                -v bp99="${local_base_p99:-0}" '
                function pct(now, base) {
                    if (base + 0 <= 0) return "—"
                    return sprintf("%+.1f%%", (now - base) / base * 100)
                }
                {
                    ts=$1; commit=$2; dirty=$3; req=$4+0; p50=$5+0; p99=$6+0; non2xx=$7; note=$8
                    if (dirty == "1") commit = commit "*"
                    drq = (br + 0 > 0) ? pct(req, br) : "—"
                    dp50 = (bp50 + 0 > 0) ? pct(p50, bp50) : "—"
                    dp99 = (bp99 + 0 > 0) ? pct(p99, bp99) : "—"
                    printf "| %s | %s | %.0f | %s | %.3f | %s | %.3f | %s | %s | %s |\n",
                        ts, commit, req, drq, p50, dp50, p99, dp99, non2xx, note
                }
            ' "$history_file"
            printf '\n'
            printf '_`*` after a commit hash means working tree was dirty when measured. Δ is vs the nginx baseline median._\n\n'
        else
            printf '### ruxen history\n\n_No measurements yet._ Run: `bench/scripts/measure.sh %s`\n\n' "$scenario"
        fi
    done
} >"$TMP"

mv "$TMP" "$OUT"
log "wrote $OUT"
